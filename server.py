def process_update(u):
    if "callback_query" in u:
        handle_callback(u["callback_query"]); return
    msg = u.get("message", {})
    cid = msg.get("chat", {}).get("id")
    if not cid:
        return
    if any(k in msg for k in ("photo", "video", "document")):
        with _plock:
            partner(cid)["last_seen"] = time.time(); _save(DB)
        handle_media(cid, msg); return
    txt = msg.get("text", "")
    if not txt:
        return
    print(f"[MSG] {cid}: {txt}", flush=True)

    # карточка партнёра: фиксируем контакт, имя, город
    with _plock:
        p = partner(cid)
        p["last_seen"] = time.time()
        capture_name_city(p, txt)
        p["stage"] = stage_by_progress(p)
        _save(DB)

    low = txt.lower().strip()

    # доступ к отчёту для Виктории
    if low.startswith("/admin"):
        if ADMIN_SECRET.lower() in low:
            with _plock:
                if cid not in DB["_admins"]:
                    DB["_admins"].append(cid)
                _save(DB)
            send_msg(cid, "Доступ открыт. Команда /svodka покажет всех партнёров и их этапы.")
        else:
            send_msg(cid, "Неверное слово доступа.")
        return
    if low.startswith("/svodka") or low in ("сводка", "отчёт", "отчет"):
        if cid in DB.get("_admins", []):
            send_msg(cid, svodka_text())
        else:
            route(cid, txt)
        return

    # команды из меню
    if low.startswith("/design") or low.startswith("/дизайн"):
        send_design(cid); return
    if low.startswith("/plans") or low.startswith("/планы"):
        send_plans(cid); return
    if low.startswith("/help") or low.startswith("/помощь"):
        send_msg(cid, "Я справочник отдела запуска Крутим Тут. Спрашивай что угодно по точке, я сразу отвечаю. Темы: "
                      "локация, аренда, ремонт, вода, вентиляция, дизайн, оборудование, электрика, касса, вывеска, "
                      "листовки, поставки, персонал, зарплата, обучение, документы, выручка, график, фудкост. "
                      "Команды: /design покажу дизайн-проекты, /plans чертежи, /start с начала.")
        return

    if txt.startswith("/start"):
        send_msg(cid, "Это справочник отдела запуска Крутим Тут. Спрашивай что угодно по открытию и работе точки — "
                      "локация, ремонт, дизайн, оборудование, касса, вывеска, персонал, выручка. Отвечаю сразу. "
                      "Команды: /design дизайн-проекты, /plans чертежи, /help все темы.")
    else:
        greeted.add(cid)
        route(cid, txt)

