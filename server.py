def partner(cid):
    k = str(cid)
    if k not in DB:
        DB[k] = {"chat_id": cid, "name": "", "city": "", "first_seen": time.time(),
                 "last_seen": time.time(), "stage": "знакомство", "checklists": {}, "reminders": []}
    return DB[k]

