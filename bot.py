def clean(text):
    text = re.sub(
        "[\U0001F000-\U0001FAFF\U00002600-\U000027BF\U0001F1E6-\U0001F1FF\U00002190-\U000021FF\U00002B00-\U00002BFF\U0000FE00-\U0000FE0F]+",
        "", text)
    text = text.replace("**", "").replace("*", "").replace("#", "").replace("`", "")
    text = re.sub(r"^\s*[-•\d]+[\.\)]\s*", "", text, flags=re.MULTILINE)
    text = re.sub(r"\n{3,}", "\n\n", text)
    text = re.sub(r"[ \t]{2,}", " ", text)
    return text.strip()

def ask_ai(text):
    if not OPENROUTER_KEY:
        return "Расскажи чуть подробнее, что именно интересует по запуску точки?"
    try:
        r = requests.post(
            "https://openrouter.ai/api/v1/chat/completions",
            headers={"Authorization": f"Bearer {OPENROUTER_KEY}", "Content-Type": "application/json"},
            json={"model": AI_MODEL,
                  "messages": [{"role": "system", "content": SYSTEM_PROMPT},
                               {"role": "user", "content": text}],
                  "max_tokens": 300},
            timeout=12)
        data = r.json()
        if "choices" in data:
            return clean(data["choices"][0]["message"]["content"].strip())
    except Exception as e:
        print(f"[AI err] {e}")
    return "Уточни вопрос парой слов, и я подскажу по делу. Что именно интересует?"

