def handle_callback(cq):
    data = cq.get("data", "")
    chat_id = cq["message"]["chat"]["id"]
    msg_id = cq["message"]["message_id"]
    cq_id = cq["id"]
    try:
        key, idx = data.split(":")
        idx = int(idx)
    except ValueError:
        requests.post(f"{API}/answerCallbackQuery", json={"callback_query_id": cq_id}, timeout=10)
        return

    s = progress.setdefault((chat_id, key), set())
    if idx in s:
        s.discard(idx)
    else:
        s.add(idx)

    # Обновляем галочки в сообщении
    requests.post(f"{API}/editMessageReplyMarkup", json={
        "chat_id": chat_id, "message_id": msg_id,
        "reply_markup": build_keyboard(chat_id, key),
    }, timeout=10)
    requests.post(f"{API}/answerCallbackQuery", json={"callback_query_id": cq_id}, timeout=10)

    # Все пункты закрыты — показываем финал один раз
    if len(s) == len(CHECKLISTS[key]["items"]) and (chat_id, key) not in done_notified:
        done_notified.add((chat_id, key))
        send_msg(chat_id, CHECKLISTS[key]["done"])

