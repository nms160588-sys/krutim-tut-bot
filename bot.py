def clean(text):
    # убрать приветствия в начале
    text = re.sub(r"^\s*(привет\w*|здравствуй\w*|здаров\w*|добрый день|добрый вечер|доброе утро)[!,.\s]*",
                  "", text, flags=re.IGNORECASE)
    # убрать эмодзи и markdown
    text = re.sub("[\U0001F000-\U0001FAFF\U00002600-\U000027BF\U0001F1E6-\U0001F1FF\U00002B00-\U00002BFF\U0000FE00-\U0000FE0F]+", "", text)
    text = text.replace("**", "").replace("*", "").replace("#", "").replace("`", "")
    text = re.sub(r"^\s*[-•\d]+[\.\)]\s*", "", text, flags=re.MULTILINE)
    text = re.sub(r"\n{3,}", "\n\n", text)
    text = re.sub(r"[ \t]{2,}", " ", text)
    return text.strip()

