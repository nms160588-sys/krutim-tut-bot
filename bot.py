# ═══════════════════════════════════════
#  ОЧИСТКА СООБЩЕНИЙ
# ═══════════════════════════════════════
def clean_response(text):
    """Очищает сообщение от лишних символов и пробелов"""
    # Убираем лишние пробелы
    text = re.sub(r'\s+', ' ', text).strip()
    # Убираем лишние пустые строки
    text = re.sub(r'\n\s*\n\s*\n+', '\n\n', text)
    # Убираем спецсимволы если их много
    text = re.sub(r'[✓✅❌🔥]{2,}', '', text)
    return text

# ═══════════════════════════════════════
#  TELEGRAM
# ═══════════════════════════════════════
def get_updates(offset=None):
    try:
        params = {"timeout": 20}
        if offset:
            params["offset"] = offset
        r = requests.get(
            f"https://api.telegram.org/bot{TELEGRAM_TOKEN}/getUpdates",
            params=params, timeout=25
        )
        return r.json()
    except Exception as e:
        print(f"[Telegram] Ошибка: {e}")
        return {}

def send_message(chat_id, text):
    try:
        requests.post(
            f"https://api.telegram.org/bot{TELEGRAM_TOKEN}/sendMessage",
            json={"chat_id": chat_id, "text": text},
            timeout=10
        )
    except Exception as e:
        print(f"[Telegram] Ошибка отправки: {e}")

# ═══════════════════════════════════════
#  AI - ВСТРОЕННАЯ БАЗА ( 100% надежна)
# ═══════════════════════════════════════
def ask_ai(text):
    text_lower = text.lower()

    # Ищем совпадение с ключевыми словами
    for keyword, answer in ANSWERS.items():
        if keyword in text_lower:
            print(f"[AI] Ответ по ключевому слову: {keyword}")
            return clean_response(answer)

    # Если ничего не найдено - общий ответ
    return clean_response(ANSWERS[""])

